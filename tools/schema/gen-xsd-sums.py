#!/usr/bin/env python3
"""Writes source/LandrixGaebXmlXsdSums.pas: the SHA-256 of every schema file
of the published contexts in tools/schema/manifest.json (main schemas and
their Lib files), for the checksum check of LandrixGaebXmlXsd. The schemas
themselves are not part of the repository; only their names and checksums
are.

Usage:
  python tools/schema/gen-xsd-sums.py           write the unit
  python tools/schema/gen-xsd-sums.py --check   exit 1 if the unit differs
"""

import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MANIFEST = os.path.join(HERE, "manifest.json")
UNIT = os.path.join(ROOT, "source", "LandrixGaebXmlXsdSums.pas")

HEADER = """{
  GAEB-for-Pascal

  Copyright (C) 2026 Landrix Software GmbH & Co. KG

  This file is dual-licensed under:
  - GNU GPL version 3 or later; or
  - the Landrix Software Commercial License.

  See LICENSE and commercial.license.md.

  SPDX-License-Identifier: GPL-3.0-or-later OR LicenseRef-Landrix-Commercial
}

{ GENERATED by tools/schema/gen-xsd-sums.py from tools/schema/manifest.json
  - do not edit; change the generator and run it again.
  DE: ERZEUGT von tools/schema/gen-xsd-sums.py aus
  tools/schema/manifest.json - nicht von Hand aendern; den Generator aendern
  und erneut ausfuehren. }

{ SHA-256 of the official GAEB DA XML schema files of every published
  target (main schema and Lib file), as published by GAEB. Only names and
  checksums, not the schemas.
  DE: SHA-256 der offiziellen GAEB-DA-XML-Schemadateien jedes
  veroeffentlichten Ziels (Hauptschema und Lib-Datei), wie vom GAEB
  veroeffentlicht. Nur Namen und Pruefsummen, nicht die Schemas. }

{ API: internal. May change in any release, also after 1.0; use the
  stable units instead (see README).
  DE: API: intern. Kann sich in jeder Version aendern, auch nach 1.0;
  stattdessen die stabilen Units verwenden (siehe README). }

unit LandrixGaebXmlXsdSums;

{$I LandrixGaeb.inc}

interface

const
"""

FOOTER = """
implementation

end.
"""


def files():
    m = json.load(io.open(MANIFEST, encoding="utf-8"))
    result = {}
    for c in m["contexts"]:
        if not c["publish"]:
            continue
        for name, sha in c["files"].items():
            if name in result and result[name] != sha:
                raise SystemExit("gen-xsd-sums: %s has two checksums" % name)
            if not re.match(r"^[0-9a-f]{64}$", sha) or not re.match(r"^[A-Za-z0-9_.\-]+$", name):
                raise SystemExit("gen-xsd-sums: unexpected entry %s" % name)
            result[name] = sha
    return sorted(result.items())


def unit_text():
    items = files()
    n = len(items)
    out = [HEADER]
    out.append("  { Number of entries. DE: Anzahl der Eintraege. }\n")
    out.append("  LandrixGaebXsdSumCount = %d;\n\n" % n)
    out.append("  { File names, sorted. DE: Dateinamen, sortiert. }\n")
    out.append("  LandrixGaebXsdSumNames: array[0..%d] of string = (\n" % (n - 1))
    out.append(",\n".join("    '%s'" % name for name, _ in items))
    out.append("\n  );\n\n")
    out.append("  { SHA-256 in lower case hex, same order. DE: SHA-256 als Hex in\n")
    out.append("    Kleinbuchstaben, gleiche Reihenfolge. }\n")
    out.append("  LandrixGaebXsdSumValues: array[0..%d] of string = (\n" % (n - 1))
    out.append(",\n".join("    '%s'" % sha for _, sha in items))
    out.append("\n  );\n")
    out.append(FOOTER)
    return "".join(out)


def main(argv):
    check = "--check" in argv[1:]
    if any(a != "--check" for a in argv[1:]):
        sys.stderr.write(__doc__)
        return 2
    text = unit_text()
    old = io.open(UNIT, encoding="utf-8", newline="").read() if os.path.exists(UNIT) else None
    if check:
        # the checkout may have CRLF (.gitattributes): compare the content
        if old is None or old.replace("\r\n", "\n") != text:
            print("gen-xsd-sums: source/LandrixGaebXmlXsdSums.pas is not up to date")
            return 1
        print("gen-xsd-sums: up to date")
        return 0
    if old is None or old.replace("\r\n", "\n") != text:
        io.open(UNIT, "w", encoding="utf-8", newline="").write(text)
    print("gen-xsd-sums: %d file(s)" % len(files()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
